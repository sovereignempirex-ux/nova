adminGatewayRouter.post('/providers', async (req, res) => {
  const body = req.body as {
    name?: string;
    slug?: string;
    baseUrl?: string;
    apiStyle?: string;
    authType?: 'none' | 'env_api_key' | 'bearer' | 'oauth2';
    capabilities?: ProviderCapability[];
    requestMethod?: 'GET' | 'POST' | 'GET/POST';
    enabled?: boolean;
    config?: Record<string, unknown>;
  };

  if (!body.name?.trim() || !body.slug?.trim() || !body.baseUrl?.trim()) {
    res.status(400).json({ error: 'name, slug, and baseUrl are required.' });
    return;
  }

  const urlCheck = await validatePublicHttpUrl(body.baseUrl);
  if (!urlCheck.ok) {
    res.status(400).json({ error: urlCheck.reason || 'baseUrl must be a valid public HTTP/HTTPS URL.' });
    return;
  }

  const created = upsertProvider({
    name: body.name,
    slug: body.slug,
    baseUrl: urlCheck.parsed.toString().replace(/\/+$/, ''),
    apiStyle: body.apiStyle,
    authType: body.authType,
    capabilities: body.capabilities,
    requestMethod: body.requestMethod,
    enabled: body.enabled ?? true,
    config: body.config,
  });

  res.status(201).json({ provider: created });
});

adminGatewayRouter.patch('/providers/:id', async (req, res) => {
  const existing = getProviderById(req.params.id);
  if (!existing) {
    res.status(404).json({ error: 'Provider not found.' });
    return;
  }

  const body = req.body as Partial<typeof existing>;
  let nextBaseUrl = existing.baseUrl;
  if (typeof body.baseUrl === 'string' && body.baseUrl.trim() !== existing.baseUrl) {
    if (body.baseUrl.trim().startsWith('internal://') && existing.baseUrl.startsWith('internal://')) {
      nextBaseUrl = existing.baseUrl;
    } else {
      const urlCheck = await validatePublicHttpUrl(body.baseUrl);
      if (!urlCheck.ok) {
        res.status(400).json({ error: urlCheck.reason || 'Invalid public HTTP/HTTPS baseUrl.' });
        return;
      }
      nextBaseUrl = urlCheck.parsed.toString().replace(/\/+$/, '');
    }
  }

  const updated = upsertProvider({
    id: existing.id,
    name: body.name ?? existing.name,
    slug: existing.slug,
    baseUrl: nextBaseUrl,
    apiStyle: body.apiStyle ?? existing.apiStyle,
    authType: body.authType ?? existing.authType,
    capabilities: body.capabilities ?? existing.capabilities,
    requestMethod: body.requestMethod ?? existing.requestMethod,
    enabled: typeof body.enabled === 'boolean' ? body.enabled : existing.enabled,
    config: body.config ?? existing.config,
    endpoints: body.endpoints ?? existing.endpoints,
  });

  res.json({ provider: updated });
});

