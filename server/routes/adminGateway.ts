adminGatewayRouter.post('/models', (req, res) => {
  const body = req.body as {
    id?: string;
    name?: string;
    providerId?: string;
    modelIdentifier?: string;
    capabilities?: ProviderCapability[];
    supportedLanguages?: string[];
    inputTypes?: Array<'text' | 'image' | 'url'>;
    outputTypes?: Array<'text' | 'image' | 'json' | 'media'>;
    streamingSupport?: boolean;
    active?: boolean;
    verified?: boolean;
    tier?: 'free' | 'paid';
    description?: string;
  };

  if (!body.id?.trim() || !body.name?.trim() || !body.providerId?.trim() || !body.modelIdentifier?.trim()) {
    res.status(400).json({ error: 'id, name, providerId, and modelIdentifier are required.' });
    return;
  }

  try {
    const created = upsertModel({
      id: body.id,
      name: body.name,
      providerId: body.providerId,
      modelIdentifier: body.modelIdentifier,
      capabilities: body.capabilities,
      supportedLanguages: body.supportedLanguages,
      inputTypes: body.inputTypes,
      outputTypes: body.outputTypes,
      streamingSupport: body.streamingSupport,
      active: body.active,
      verified: body.verified,
      tier: body.tier,
      description: body.description,
    });
    res.status(201).json({ model: created });
  } catch (err) {
    res.status(400).json({ error: err instanceof Error ? err.message : 'Failed to create model.' });
  }
});

adminGatewayRouter.patch('/models/:id', (req, res) => {
  const existing = getModelById(req.params.id);
  if (!existing) {
    res.status(404).json({ error: 'Model not found.' });
    return;
  }

  const body = req.body as Partial<typeof existing>;
  try {
    const updated = upsertModel({
      ...existing,
      ...body,
      id: existing.id,
      providerId: body.providerId ?? existing.providerId,
      name: body.name ?? existing.name,
      modelIdentifier: body.modelIdentifier ?? existing.modelIdentifier,
    });
    res.json({ model: updated });
  } catch (err) {
    res.status(400).json({ error: err instanceof Error ? err.message : 'Failed to update model.' });
  }
});

