adminGatewayRouter.post('/fallbacks', (req, res) => {
  const body = req.body as {
    capability?: ProviderCapability;
    primaryProviderSlug?: string;
    primaryModelId?: string;
    fallbackProviderSlug?: string;
    fallbackModelId?: string;
    requireCompatibleIo?: boolean;
    priority?: number;
    enabled?: boolean;
  };

  if (!body.capability || !body.primaryProviderSlug || !body.fallbackProviderSlug || !body.fallbackModelId) {
    res.status(400).json({ error: 'capability, primaryProviderSlug, fallbackProviderSlug, and fallbackModelId are required.' });
    return;
  }

  try {
    const rule = upsertFallbackRule({
      capability: body.capability,
      primaryProviderSlug: body.primaryProviderSlug,
      primaryModelId: body.primaryModelId,
      fallbackProviderSlug: body.fallbackProviderSlug,
      fallbackModelId: body.fallbackModelId,
      requireCompatibleIo: body.requireCompatibleIo ?? true,
      priority: body.priority ?? 1,
      enabled: body.enabled ?? true,
    });
    res.status(201).json({ rule });
  } catch (err) {
    res.status(400).json({ error: err instanceof Error ? err.message : 'Invalid fallback rule.' });
  }
});

adminGatewayRouter.delete('/fallbacks/:id', (req, res) => {
  const removed = deleteFallbackRule(req.params.id);
  if (!removed) {
    res.status(404).json({ error: 'Fallback rule not found.' });
    return;
  }
  res.json({ deleted: true });
});

adminGatewayRouter.get('/logs', (req, res) => {
  const providerSlug = typeof req.query.provider === 'string' ? req.query.provider : undefined;
  const errorsOnly = req.query.errorsOnly === 'true';
  const searchQuery = typeof req.query.q === 'string' ? req.query.q.trim().toLowerCase() : '';
  let logs = getGatewayLogs({ providerSlug, errorsOnly, limit: 200 });
  if (searchQuery) {
    logs = logs.filter(
      (l) =>
        l.requestId.toLowerCase().includes(searchQuery) ||
        l.providerSlug.toLowerCase().includes(searchQuery) ||
        l.modelId.toLowerCase().includes(searchQuery) ||
        l.endpoint.toLowerCase().includes(searchQuery) ||
        (l.errorMessage && l.errorMessage.toLowerCase().includes(searchQuery))
    );
  }
  res.json({ logs: logs.slice(0, 150), usage: getUsageStatistics() });
});

