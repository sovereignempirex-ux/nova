import { Router } from 'express';
import { getAutoGeneratedApiDocs } from '../gateway/gateway.ts';
import { listModels, listProviders } from '../gateway/registry.ts';
import { redactSensitiveObject } from '../gateway/reliability.ts';
import { getRouterStatusSummary } from '../gateway/router.ts';

export const gatewayPublicRouter = Router();

// Public non-secret catalog of active providers & models
gatewayPublicRouter.get('/catalog', (_req, res) => {
  const activeProviders = listProviders()
    .filter((p) => p.enabled)
    .map((p) => ({
      id: p.id,
      name: p.name,
      slug: p.slug,
      apiStyle: p.apiStyle,
      capabilities: p.capabilities,
      healthStatus: p.healthStatus,
      availabilityStatus: p.availabilityStatus,
    }));

  const activeModels = listModels({ activeOnly: true }).map((m) => ({
    id: m.id,
    name: m.name,
    providerSlug: m.providerSlug,
    capabilities: m.capabilities,
    supportedLanguages: m.supportedLanguages,
    inputTypes: m.inputTypes,
    outputTypes: m.outputTypes,
    streamingSupport: m.streamingSupport,
    verified: m.verified,
    tier: m.tier,
    description: m.description,
  }));

  res.json({
    success: true,
    providers: activeProviders,
    models: activeModels,
  });
});

gatewayPublicRouter.get('/router/status', (_req, res) => {
  res.json({
    success: true,
    router: getRouterStatusSummary(),
  });
});

// Auto-maintained public API documentation (secrets excluded)
gatewayPublicRouter.get('/docs', (_req, res) => {
  const docs = getAutoGeneratedApiDocs();
  res.json(redactSensitiveObject(docs));
});
